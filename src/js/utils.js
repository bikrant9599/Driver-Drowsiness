/* Format seconds into readable English duration (e.g. "12 minutes" or "45 seconds") */
export function formatDurationText(totalSeconds) {
  const numSecs = typeof totalSeconds === "number" && !isNaN(totalSeconds) ? Math.max(0, Math.round(totalSeconds)) : 0;
  const mins = Math.floor(numSecs / 60);
  const secs = numSecs % 60;

  if (mins === 0) {
    return `${secs} ${secs === 1 ? "second" : "seconds"}`;
  }
  if (secs === 0) {
    return `${mins} ${mins === 1 ? "minute" : "minutes"}`;
  }
  return `${mins} ${mins === 1 ? "minute" : "minutes"} ${secs} ${secs === 1 ? "second" : "seconds"}`;
}

/* Format seconds into digital mm:ss timer display */
export function formatTimerDisplay(totalSeconds) {
  const numSecs = typeof totalSeconds === "number" && !isNaN(totalSeconds) ? Math.max(0, Math.floor(totalSeconds)) : 0;
  const mins = Math.floor(numSecs / 60).toString().padStart(2, "0");
  const secs = (numSecs % 60).toString().padStart(2, "0");
  return `${mins}:${secs}`;
}

/* Format timestamp into readable date & time (e.g. "16 Oct 2026 · 10:30 PM") */
export function formatDateTime(timestamp) {
  const date = timestamp ? new Date(timestamp) : new Date();
  if (isNaN(date.getTime())) return "Unknown Date";

  const day = date.getDate();
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const month = months[date.getMonth()];
  const year = date.getFullYear();

  let hours = date.getHours();
  const minutes = date.getMinutes().toString().padStart(2, "0");
  const ampm = hours >= 12 ? "PM" : "AM";
  hours = hours % 12;
  hours = hours ? hours : 12; // 0 converted to 12

  return `${day} ${month} ${year} · ${hours}:${minutes} ${ampm}`;
}
