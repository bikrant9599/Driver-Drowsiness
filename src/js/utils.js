/* Format seconds into MM:SS or HH:MM:SS */
export function formatDuration(totalSeconds) {
  const numSecs = typeof totalSeconds === "number" && !isNaN(totalSeconds) ? Math.max(0, Math.round(totalSeconds)) : 0;
  const hrs = Math.floor(numSecs / 3600);
  const mins = Math.floor((numSecs % 3600) / 60);
  const secs = Math.floor(numSecs % 60);
  const pad = (n) => String(n).padStart(2, "0");
  if (hrs > 0) {
    return `${pad(hrs)}:${pad(mins)}:${pad(secs)}`;
  }
  return `${pad(mins)}:${pad(secs)}`;
}

/* Format Date nicely */
export function formatDateTime(isoString) {
  if (!isoString) return "N/A";
  const d = new Date(isoString);
  if (isNaN(d.getTime())) return "N/A";
  return d.toLocaleString("en-US", {
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: true
  });
}

/* Toast Notifications */
export function showToast(title, message, type = "info", duration = 3500) {
  let container = document.getElementById("toast-container");
  if (!container) {
    container = document.createElement("div");
    container.id = "toast-container";
    document.body.appendChild(container);
  }

  const toast = document.createElement("div");
  toast.className = `toast toast-${type}`;

  let iconSvg = ICONS.info;
  if (type === "danger") iconSvg = ICONS.alertTriangle;
  if (type === "safe") iconSvg = ICONS.shieldCheck;

  toast.innerHTML = `
    <div class="toast-icon">${iconSvg}</div>
    <div class="toast-content">
      <div class="toast-title">${title}</div>
      <div class="toast-message">${message}</div>
    </div>
    <button class="toast-close" aria-label="Close">${ICONS.close}</button>
  `;

  const closeBtn = toast.querySelector(".toast-close");
  closeBtn.addEventListener("click", () => toast.remove());

  container.appendChild(toast);

  if (duration > 0) {
    setTimeout(() => {
      if (toast.parentElement) {
        toast.style.opacity = "0";
        toast.style.transform = "translateX(20px)";
        toast.style.transition = "all 0.25s ease";
        setTimeout(() => toast.remove(), 250);
      }
    }, duration);
  }
}

/* Confirmation Modal Helper */
export function showConfirmModal({ title, message, confirmText = "Confirm", cancelText = "Cancel", isDanger = false, onConfirm }) {
  let overlay = document.getElementById("global-modal-overlay");
  if (!overlay) {
    overlay = document.createElement("div");
    overlay.id = "global-modal-overlay";
    overlay.className = "modal-overlay";
    document.body.appendChild(overlay);
  }

  overlay.innerHTML = `
    <div class="modal-dialog" style="max-width: 440px;">
      <div class="modal-header">
        <div class="modal-title">${isDanger ? ICONS.alertTriangle : ICONS.info} <span>${title}</span></div>
        <button class="modal-close-btn" id="modal-cancel-x">${ICONS.close}</button>
      </div>
      <div class="modal-body" style="padding: 1.25rem; font-size: 0.9rem; line-height: 1.5; color: var(--text-secondary);">${message}</div>
      <div class="modal-footer" style="padding: 1rem 1.25rem; display: flex; justify-content: flex-end; gap: 0.5rem; border-top: 1px solid var(--border-subtle);">
        <button class="btn btn-secondary" id="modal-cancel-btn">${cancelText}</button>
        <button class="btn ${isDanger ? 'btn-danger' : 'btn-primary'}" id="modal-confirm-btn">${confirmText}</button>
      </div>
    </div>
  `;

  overlay.classList.add("open");

  const close = () => {
    overlay.classList.remove("open");
  };

  overlay.querySelector("#modal-cancel-x").onclick = close;
  overlay.querySelector("#modal-cancel-btn").onclick = close;
  overlay.querySelector("#modal-confirm-btn").onclick = () => {
    close();
    if (typeof onConfirm === "function") onConfirm();
  };
  overlay.onclick = (e) => {
    if (e.target === overlay) close();
  };
}
